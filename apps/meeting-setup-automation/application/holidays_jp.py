#: 日本の祝日(国民の祝日・振替休日・国民の休日を含む)の固定集合。カバー範囲は2018〜2032年。
HOLIDAYS = frozenset(
    date.fromisoformat(iso)
    for isos in _HOLIDAY_DATES_BY_YEAR.values()
    for iso in isos
)
_COVERED_YEARS = frozenset(_HOLIDAY_DATES_BY_YEAR)


class 祝日テーブル範囲外(Exception):
    """祝日テーブルがカバーしていない年の日付。黙って平日と判定しないための例外。"""


def covers(d):
    """dの年が祝日テーブルの範囲内ならTrue。"""
    return d.year in _COVERED_YEARS


def _範囲を確認(d):
    if not covers(d):
        年一覧 = sorted(_COVERED_YEARS)
        raise 祝日テーブル範囲外(
            f"{d.isoformat()} は祝日テーブルの範囲外です(対応範囲: {年一覧[0]}〜{年一覧[-1]}年)。"
            "holidays_jp.py のテーブルを追記してください"
        )


def is_holiday(d):
    """dが日本の祝日ならTrue。テーブル範囲外の年は例外にする。"""
    _範囲を確認(d)
    return d in HOLIDAYS


def is_weekend(d):
    """dが土曜または日曜ならTrue。"""
    return d.weekday() >= 5


def is_non_working_day(d):
    """dが休業日(土曜・日曜・祝日のいずれか)ならTrue。テーブル範囲外の年は例外にする。"""
    return is_weekend(d) or is_holiday(d)
