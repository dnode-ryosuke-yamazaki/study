"""1回の実行を組み立てるエントリポイント。

処理の順序が仕様上重要な点が1つある。**「使用するURLの一覧の決定」を「未取得の
判定」より先に行う。** その録画に何件のトランスクリプトが存在するかの正は台帳では
なく直近の発行時点の一覧であり、台帳の件数を正にすると、フロー②が2件発行しても
台帳が1件なら1件保存した時点で完了と判定して台帳を消してしまう
(requirements.md#トランスクリプトの列挙 [1])。

対応する仕様:
- design.md#台帳の読み取りと使用するURLの一覧の決定(バッチ)
- design.md#未取得の判定(バッチ)
- design.md#トランスクリプトの取得と保存(バッチ)
- design.md#台帳と要求のライフサイクル
"""

from __future__ import annotations

import logging
import logging.handlers
import sys
from dataclasses import dataclass, field
from datetime import datetime, timedelta, timezone
from pathlib import Path

import config
import downloader
import ledger
import naming
import state
import status_log
import writer

logger = logging.getLogger(__name__)

#: URLの出所。検証項目1(URLの寿命)を観測するためログに出す。
出所_url置き場 = "url置き場"
出所_台帳 = "台帳"
出所_なし = "なし"


@dataclass
class 実行結果:
    台帳の件数: int = 0
    成功件数: int = 0
    スキップ件数: int = 0
    恒久的失敗件数: int = 0
    一時的失敗件数: int = 0
    要発行件数: int = 0
    退避件数: int = 0
    要手動確認件数: int = 0
    発行要求件数: int = 0
    要求の退避件数: int = 0
    中断した: bool = False
    中断の理由: str = ""
    記録した行: list[status_log.記録する行] = field(default_factory=list)


@dataclass
class _処理対象:
    """1つの録画について、この実行で使う情報をまとめたもの。"""

    台帳: ledger.台帳
    url一覧: list[str]
    発行時刻: datetime | None
    出所: str
    既知件数: int
    url情報: ledger.url情報 | None
    要発行: bool
    要発行の理由: str = ""


def ログを設定する(設定: config.設定) -> None:
    """ログをローカルのファイルへ出す(同期フォルダには置かない)。

    既定はDEBUG。検証項目の観測に使う項目がDEBUGで出るため、既定をINFOにすると
    観測自体が成立しない(design.md#ログ)。
    """
    ルート = logging.getLogger()
    if ルート.handlers:
        return
    ルート.setLevel(設定.ログレベル)
    設定.ログファイル.parent.mkdir(parents=True, exist_ok=True)
    ファイル出力 = logging.handlers.RotatingFileHandler(
        設定.ログファイル, maxBytes=1_000_000, backupCount=5, encoding="utf-8"
    )
    ファイル出力.setFormatter(
        logging.Formatter("%(asctime)s %(levelname)s %(name)s %(message)s")
    )
    ルート.addHandler(ファイル出力)


def _使用するurlの一覧を決める(
    台帳: ledger.台帳, 設定: config.設定, 状態: state.状態, 現在時刻: datetime
) -> _処理対象:
    """使用するURLの一覧と既知件数を確定させる。

    分岐は「台帳のURL有無 × URLファイルの有無」の2×2を覆う。とくに
    **「台帳にURLがなく、URLファイルがある」はフェーズ2の主経路**であり、
    台帳側に比較対象の発行時刻が存在しないため新旧比較に含めてはならない。
    含めると条件が成立せず、発行されたURLを永久に消費しない。
    """
    url情報 = ledger.url情報を読む(設定.urlフォルダ, 台帳.録画の識別子)
    録画の状態 = 状態.録画の状態(台帳.録画の識別子)

    台帳にurlがある = bool(台帳.url一覧)
    urlファイルがある = url情報 is not None and bool(url情報.url一覧)

    if not 台帳にurlがある and urlファイルがある:
        使うurl一覧, 使う発行時刻, 出所 = url情報.url一覧, url情報.発行時刻, 出所_url置き場
    elif 台帳にurlがある and urlファイルがある:
        # 新旧比較。発行時刻が無いものは古いものとして扱う。
        台帳の方が新しい = (台帳.発行時刻 or datetime.min.replace(tzinfo=timezone.utc)) >= (
            url情報.発行時刻 or datetime.min.replace(tzinfo=timezone.utc)
        )
        if 台帳の方が新しい:
            使うurl一覧, 使う発行時刻, 出所 = 台帳.url一覧, 台帳.発行時刻, 出所_台帳
        else:
            使うurl一覧, 使う発行時刻, 出所 = (
                url情報.url一覧,
                url情報.発行時刻,
                出所_url置き場,
            )
    elif 台帳にurlがある:
        使うurl一覧, 使う発行時刻, 出所 = 台帳.url一覧, 台帳.発行時刻, 出所_台帳
    else:
        使うurl一覧, 使う発行時刻, 出所 = [], None, 出所_なし

    要発行 = False
    理由 = ""

    if 出所 == 出所_なし:
        要発行, 理由 = True, "有効なダウンロードURLがない"
    elif 使う発行時刻 is not None and 録画の状態.発行時刻は死んでいるか(使う発行時刻):
        要発行, 理由 = True, "同じURLは既に恒久的失敗と判定済み"
    elif 使う発行時刻 is not None and 現在時刻 - 使う発行時刻 > timedelta(
        minutes=設定.url期限しきい値分
    ):
        要発行, 理由 = True, f"発行から{設定.url期限しきい値分}分を超えている"
        # 古いままでは次サイクルでも同じ判定になるため落とす。
        if url情報 is not None:
            url情報.パス.unlink(missing_ok=True)

    # 既知件数は単調非減少に保つ。減ると「全件保存済み」と誤判定し、台帳が
    # 削除されて残りを永久に取りこぼす(requirements.md#トランスクリプトの列挙 [5])。
    既知件数 = max(len(使うurl一覧), 録画の状態.既知件数の最大値)
    録画の状態.既知件数の最大値 = 既知件数

    if not 要発行 and len(使うurl一覧) < 既知件数:
        要発行, 理由 = True, f"既知件数{既知件数}件に対しURLが{len(使うurl一覧)}件しかない"

    経過の表示 = (
        f"{(現在時刻 - 使う発行時刻).total_seconds() / 60:.1f}分"
        if 使う発行時刻
        else "不明"
    )
    # 検証項目1(URLの寿命)の観測用。
    logger.info(
        "URLの鮮度: 録画=%s 出所=%s 発行からの経過=%s",
        台帳.録画の識別子,
        出所,
        経過の表示,
    )
    # 検証項目2・8の観測用。既知件数とURL数の差が件数不足の観測になる。
    logger.debug(
        "台帳の項目: 録画=%s 項目=%s 既知件数=%d URL数=%d",
        台帳.録画の識別子,
        sorted(
            項目
            for 項目, 値 in (
                ("meetingName", 台帳.会議名),
                ("recordingCreatedAt", 台帳.録画の作成日時),
                ("source", 台帳.由来),
                ("issuedAt", 台帳.発行時刻),
            )
            if 値
        ),
        既知件数,
        len(使うurl一覧),
    )

    return _処理対象(
        台帳=台帳,
        url一覧=使うurl一覧,
        発行時刻=使う発行時刻,
        出所=出所,
        既知件数=既知件数,
        url情報=url情報,
        要発行=要発行,
        要発行の理由=理由,
    )


def _未取得の並び順を求める(
    対象: _処理対象, 設定: config.設定, 状態: state.状態
) -> list[int]:
    """まだ保存していないトランスクリプトの並び順を返す。"""
    未取得 = []
    for 並び順 in range(対象.既知件数):
        識別子 = state.トランスクリプトの識別子(対象.台帳.録画の識別子, 並び順)
        if 状態.取得済みか(識別子):
            continue
        # 出力置き場に同名ファイルがあれば取得済みとして扱う。取得済み記録が
        # 失われた場合の二重取得をここで受け止める。
        ファイル名 = _出力ファイル名(対象, 並び順)
        if (設定.出力フォルダ / ファイル名).exists():
            # 自分が記録していないファイルが同名で存在する場合、
            # (a)取得済み記録が失われた か (b)別の録画とファイル名が衝突した
            # のどちらか。(b)だとこの録画のトランスクリプトを取り逃すため、
            # 黙って飛ばさずログに残す。出力ファイル名は会議名と時刻(分まで)と
            # 連番だけで決まるので、同名・同分の別録画では一致しうる。
            logger.warning(
                "出力置き場に同名ファイルがあるため取得済みとして扱う: 録画=%s 出力=%s "
                "(取得済み記録に無いため、記録の消失か別録画との名前衝突の可能性)",
                対象.台帳.録画の識別子,
                ファイル名,
            )
            状態.取得済みにする(識別子, datetime.now(timezone.utc))
            continue
        未取得.append(並び順)
    return 未取得


def _出力ファイル名(対象: _処理対象, 並び順: int) -> str:
    時刻 = naming.ファイル名の時刻を決める(
        対象.台帳.録画の作成日時, 対象.台帳.更新時刻
    )
    return naming.出力ファイル名(対象.台帳.会議名, 時刻, 並び順 + 1)


def _時刻の表示(対象: _処理対象) -> str:
    時刻 = naming.ファイル名の時刻を決める(対象.台帳.録画の作成日時, 対象.台帳.更新時刻)
    return 時刻.astimezone().strftime("%Y-%m-%d %H:%M")


def _記録すべきか(録画の状態: state.録画の状態, ラベル: str) -> bool:
    """同じ対象の同じ失敗を繰り返し追記しないための判定。"""
    if 録画の状態.記録済みか(ラベル):
        return False
    録画の状態.記録済みにする(ラベル)
    return True


def 実行する(設定: config.設定, *, 現在時刻: datetime | None = None) -> 実行結果:
    """台帳を読み、URLを消費してトランスクリプトを保存する1サイクル。"""
    今 = 現在時刻 or datetime.now(timezone.utc)
    結果 = 実行結果()

    読んだ状態 = state.読み込む(設定.状態ファイル)

    try:
        読み込み = ledger.台帳を読み込む(設定.台帳フォルダ)
    except ledger.台帳置き場にアクセスできない as 例外:
        # 「台帳が0件」と区別する。同期フォルダが見つからない状態で何もしないと
        # 異常に気づかないまま静かに止まる。
        logger.error("台帳置き場にアクセスできないため全体を中断する: %s", 例外)
        結果.中断した = True
        結果.中断の理由 = str(例外)
        return 結果

    結果.台帳の件数 = len(読み込み.有効)
    logger.info("実行開始: 台帳=%d件 不正=%d件", len(読み込み.有効), len(読み込み.不正))

    for 不正 in 読み込み.不正:
        ledger.退避する(不正.パス, 設定.退避フォルダ)
        結果.退避件数 += 1
        結果.記録した行.append(
            status_log.記録する行(
                ラベル=status_log.ラベル_台帳が不正,
                会議名=不正.パス.name,
                時刻の表示="-",
                詳細=不正.理由,
            )
        )

    対象たち = [
        _使用するurlの一覧を決める(台帳, 設定, 読んだ状態, 今)
        for 台帳 in 読み込み.有効
    ]

    # 発行時刻の新しい順。URLの寿命が短いため、古いものから処理すると
    # 新しいものが上限件数に阻まれて寿命内に消費できなくなる。
    最古 = datetime.min.replace(tzinfo=timezone.utc)
    対象たち.sort(key=lambda 対象: 対象.発行時刻 or 最古, reverse=True)

    試行した件数 = 0
    for 対象 in 対象たち:
        録画の状態 = 読んだ状態.録画の状態(対象.台帳.録画の識別子)

        if 録画の状態.初回観測 is None:
            録画の状態.初回観測 = 今

        # 「要手動確認」の録画は処理対象から除外し、上限件数も消費しない。
        if 録画の状態.恒久的失敗の回数 >= 設定.恒久的失敗の上限:
            結果.要手動確認件数 += 1
            logger.debug("要手動確認のためスキップ: 録画=%s", 対象.台帳.録画の識別子)
            if _記録すべきか(録画の状態, status_log.ラベル_取得失敗):
                結果.記録した行.append(
                    status_log.記録する行(
                        ラベル=status_log.ラベル_取得失敗,
                        会議名=対象.台帳.会議名,
                        時刻の表示=_時刻の表示(対象),
                        詳細=f"恒久的失敗が{設定.恒久的失敗の上限}回に達したため要手動確認",
                    )
                )
            continue

        未取得 = _未取得の並び順を求める(対象, 設定, 読んだ状態)

        if not 未取得 and not 対象.要発行:
            # 既知の全件を保存し終えた。台帳と使用済みURLを片付けて完了。
            _完了として片付ける(対象, 読んだ状態)
            continue

        if 対象.要発行:
            結果.要発行件数 += 1
            _発行を要求する(対象, 設定, 読んだ状態, 結果, 今)
            continue

        if 試行した件数 >= 設定.処理上限件数:
            logger.info("処理上限%d件に達したため残りを次回に委ねる", 設定.処理上限件数)
            break

        試行した件数 += 1
        _1つの録画を処理する(対象, 未取得, 設定, 読んだ状態, 結果, 今)

    _滞留した要求を退避する(設定, 結果, 今)
    _長期滞留を記録する(対象たち, 読んだ状態, 設定, 結果, 今)

    state.保存する(読んだ状態, 設定.状態ファイル)
    status_log.追記する(設定.記録ファイル, 結果.記録した行, 今)

    logger.info(
        "実行終了: 成功=%d スキップ=%d 恒久的失敗=%d 一時的失敗=%d "
        "要発行=%d 発行要求=%d 退避=%d 要求退避=%d",
        結果.成功件数,
        結果.スキップ件数,
        結果.恒久的失敗件数,
        結果.一時的失敗件数,
        結果.要発行件数,
        結果.発行要求件数,
        結果.退避件数,
        結果.要求の退避件数,
    )
    return 結果


def _1つの録画を処理する(
    対象: _処理対象,
    未取得: list[int],
    設定: config.設定,
    読んだ状態: state.状態,
    結果: 実行結果,
    今: datetime,
) -> None:
    """1つの録画の未保存トランスクリプトを取得して保存する。

    1件の失敗が他の対象の処理を止めないよう、例外は捕まえて次へ進む。
    """
    録画の状態 = 読んだ状態.録画の状態(対象.台帳.録画の識別子)
    この実行で恒久的失敗を数えた = False

    for 並び順 in 未取得:
        if 並び順 >= len(対象.url一覧):
            continue
        try:
            取得結果 = downloader.取得する(
                対象.url一覧[並び順],
                タイムアウト秒=設定.タイムアウト秒,
                許可するホスト接尾辞=設定.許可するホスト接尾辞,
            )
        except Exception:
            # 想定外の例外でもプロセス全体を落とさない。
            logger.exception("取得中に想定外の例外: 録画=%s", 対象.台帳.録画の識別子)
            結果.一時的失敗件数 += 1
            continue

        経過の表示 = (
            f"{(今 - 対象.発行時刻).total_seconds() / 60:.1f}分"
            if 対象.発行時刻
            else "不明"
        )

        if isinstance(取得結果, downloader.一時的失敗):
            結果.一時的失敗件数 += 1
            logger.info(
                "一時的失敗: 録画=%s 理由=%s", 対象.台帳.録画の識別子, 取得結果.理由
            )
            # 一時的失敗は通常記録しない(次回に自然とリトライされるため)。
            # ただしローカルの設定不足は待っても直らず、記録しないと利用者には
            # 「何も起きない」ことしか分からないので1回だけ残す。
            if 取得結果.設定の問題 and _記録すべきか(
                録画の状態, status_log.ラベル_設定の問題
            ):
                logger.error("設定の問題で取得できない: %s", 取得結果.理由)
                結果.記録した行.append(
                    status_log.記録する行(
                        ラベル=status_log.ラベル_設定の問題,
                        会議名=対象.台帳.会議名,
                        時刻の表示=_時刻の表示(対象),
                        詳細=(
                            f"{取得結果.理由} / 待っても直りません。"
                            "READMEの「証明書のセットアップ」を確認してください"
                        ),
                    )
                )
            continue

        if isinstance(取得結果, downloader.恒久的失敗):
            結果.恒久的失敗件数 += 1
            # 回数は録画単位・1実行につき最大1回。トランスクリプトごとに数えると
            # 一覧がまとめて期限切れになった1回の実行で即座に上限へ達してしまう。
            if not この実行で恒久的失敗を数えた:
                録画の状態.恒久的失敗の回数 += 1
                この実行で恒久的失敗を数えた = True
            if 対象.発行時刻 is not None:
                録画の状態.死んだ発行時刻に加える(対象.発行時刻)
            if 対象.url情報 is not None:
                対象.url情報.パス.unlink(missing_ok=True)
            logger.warning(
                "恒久的失敗: 録画=%s 理由=%s 累積=%d回 発行からの経過=%s",
                対象.台帳.録画の識別子,
                取得結果.理由,
                録画の状態.恒久的失敗の回数,
                経過の表示,
            )
            if _記録すべきか(録画の状態, status_log.ラベル_取得失敗):
                結果.記録した行.append(
                    status_log.記録する行(
                        ラベル=status_log.ラベル_取得失敗,
                        会議名=対象.台帳.会議名,
                        時刻の表示=_時刻の表示(対象),
                        詳細=取得結果.理由,
                    )
                )
            continue

        ファイル名 = _出力ファイル名(対象, 並び順)
        try:
            書き出し結果 = writer.書き出す(取得結果.本文, 設定.出力フォルダ, ファイル名)
        except writer.書き出し先が不正 as 例外:
            結果.恒久的失敗件数 += 1
            logger.error("書き出し先が不正: %s", 例外)
            continue
        except OSError:
            結果.一時的失敗件数 += 1
            logger.exception("書き出しに失敗: %s", ファイル名)
            continue

        識別子 = state.トランスクリプトの識別子(対象.台帳.録画の識別子, 並び順)
        読んだ状態.取得済みにする(識別子, 今)

        if isinstance(書き出し結果, writer.既にあった):
            結果.スキップ件数 += 1
        else:
            結果.成功件数 += 1
            logger.info(
                "取得成功: 録画=%s 出力=%s %dバイト 発行からの経過=%s",
                対象.台帳.録画の識別子,
                ファイル名,
                書き出し結果.バイト数,
                経過の表示,
            )

    # 保存が進んだので、進捗のない発行要求の連続回数は0に戻す。
    if 結果.成功件数 or 結果.スキップ件数:
        録画の状態.進捗なし発行要求の回数 = 0

    残り = _未取得の並び順を求める(対象, 設定, 読んだ状態)
    if not 残り:
        _完了として片付ける(対象, 読んだ状態)


def _発行を要求する(
    対象: _処理対象,
    設定: config.設定,
    読んだ状態: state.状態,
    結果: 実行結果,
    今: datetime,
) -> None:
    """有効なURLがない録画について、ダウンロードURLの発行を要求する。

    フェーズ1では「記録に残して終端」だったが、フェーズ2ではここから
    Power Automateのフロー②に発行を依頼する。これによりPCを止めていた期間の
    取りこぼしがなくなる(requirements.md#エラー時の挙動 [3])。
    """
    録画の状態 = 読んだ状態.録画の状態(対象.台帳.録画の識別子)

    # 進捗のない要求を出し続けないための打ち切り。恒久的失敗の上限とは別の経路で、
    # 「トランスクリプトが永久に0件」などがここで終端する。
    if 録画の状態.進捗なし発行要求の回数 >= 設定.進捗なし発行要求の上限:
        結果.要手動確認件数 += 1
        if _記録すべきか(録画の状態, status_log.ラベル_設定の問題 + "-打ち切り"):
            ラベル = (
                status_log.ラベル_トランスクリプト0件
                if 対象.既知件数 == 0
                else status_log.ラベル_件数不足
            )
            分 = 設定.進捗なし発行要求の上限 * 設定.実行間隔秒 // 60
            logger.error(
                "進捗のない発行要求が上限に達したため打ち切る: 録画=%s",
                対象.台帳.録画の識別子,
            )
            結果.記録した行.append(
                status_log.記録する行(
                    ラベル=ラベル,
                    会議名=対象.台帳.会議名,
                    時刻の表示=_時刻の表示(対象),
                    詳細=(
                        f"発行を{設定.進捗なし発行要求の上限}回(約{分}分)要求しても"
                        f"保存が進まないため要手動確認。{対象.要発行の理由}"
                    ),
                )
            )
        return

    if ledger.要求済みか(設定.要求フォルダ, 対象.台帳.録画の識別子):
        logger.debug("既に要求済みのため見送る: 録画=%s", 対象.台帳.録画の識別子)
        return

    ledger.要求を書き出す(設定.要求フォルダ, 対象.台帳, 今)
    録画の状態.進捗なし発行要求の回数 += 1
    結果.発行要求件数 += 1
    logger.info(
        "発行を要求した: 録画=%s 理由=%s 累積=%d回",
        対象.台帳.録画の識別子,
        対象.要発行の理由,
        録画の状態.進捗なし発行要求の回数,
    )


def _滞留した要求を退避する(
    設定: config.設定, 結果: 実行結果, 今: datetime
) -> None:
    """長く残っている要求を退避する。

    フロー②が解析できない要求は削除されない。放置するとその録画は
    「要求済み」扱いのまま永久に再要求されなくなるため、しきい値を超えたら
    退避して対象を解放する(requirements.md#ダウンロードURLの発行要求 [5])。
    """
    しきい値 = timedelta(minutes=設定.要求滞留しきい値分)
    for 要求 in ledger.未処理の要求を読む(設定.要求フォルダ):
        基準 = 要求.作成時刻
        if 基準 is None:
            # 解析できない要求。ファイルの更新時刻で代わりに判断する。
            基準 = datetime.fromtimestamp(要求.パス.stat().st_mtime, tz=timezone.utc)
        滞留 = 今 - 基準
        if 滞留 < しきい値:
            continue
        logger.warning(
            "要求が%d分以上未処理のため退避する: %s(フロー②が動いていない可能性)",
            設定.要求滞留しきい値分,
            要求.パス.name,
        )
        ledger.退避する(要求.パス, 設定.退避フォルダ)
        結果.要求の退避件数 += 1
        結果.記録した行.append(
            status_log.記録する行(
                ラベル=status_log.ラベル_長期滞留,
                会議名=要求.録画の識別子,
                時刻の表示="-",
                詳細=(
                    f"発行要求が{int(滞留.total_seconds() // 60)}分未処理のため退避した。"
                    "Power Automateのフロー②が動いているか確認してください"
                ),
            )
        )


def _完了として片付ける(対象: _処理対象, 読んだ状態: state.状態) -> None:
    """既知の全件を保存し終えた録画の台帳とURLファイルを削除する。

    仕様: design.md#台帳と要求のライフサイクル(1行目)
    """
    対象.台帳.パス.unlink(missing_ok=True)
    if 対象.url情報 is not None:
        対象.url情報.パス.unlink(missing_ok=True)
    読んだ状態.録画の状態を消す(対象.台帳.録画の識別子)
    logger.info("全件を保存し終えたため台帳を削除した: 録画=%s", 対象.台帳.録画の識別子)


def _長期滞留を記録する(
    対象たち: list[_処理対象],
    読んだ状態: state.状態,
    設定: config.設定,
    結果: 実行結果,
    今: datetime,
) -> None:
    """長く処理されないまま残っている台帳を記録する。

    発行要求が届いていない・Power Automateが停止しているなど、失敗として
    現れない異常を検知する手段が他にない(requirements.md#処理結果の記録 [4])。
    """
    しきい値 = timedelta(days=設定.長期滞留しきい値日)
    for 対象 in 対象たち:
        if not 対象.台帳.パス.exists():
            continue
        録画の状態 = 読んだ状態.録画の状態(対象.台帳.録画の識別子)
        初回観測 = 録画の状態.初回観測
        if 初回観測 is None or 今 - 初回観測 < しきい値:
            continue
        if _記録すべきか(録画の状態, status_log.ラベル_長期滞留):
            滞留日数 = (今 - 初回観測).days
            logger.warning(
                "長期滞留: 録画=%s %d日", 対象.台帳.録画の識別子, 滞留日数
            )
            結果.記録した行.append(
                status_log.記録する行(
                    ラベル=status_log.ラベル_長期滞留,
                    会議名=対象.台帳.会議名,
                    時刻の表示=_時刻の表示(対象),
                    詳細=f"{滞留日数}日間処理されていない",
                )
            )


def main() -> int:
    設定 = config.load()
    ログを設定する(設定)
    try:
        with state.ロック(設定.ロックファイル):
            結果 = 実行する(設定)
    except state.先行実行が動作中 as 例外:
        logger.info("先行実行が動作中のため終了する: %s", 例外)
        return 0
    return 1 if 結果.中断した else 0


if __name__ == "__main__":
    sys.exit(main())
