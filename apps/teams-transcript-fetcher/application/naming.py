"""識別子の規則と、出力ファイル名の組み立て。

前半(識別子)は Power Automateフロー①・フロー②・バッチの3者が共有する唯一の
取り決めであり、ずれても例外は出ず「URLが見つからない」だけで静かに壊れる。
変更するときは3箇所を同時に変える必要がある。

対応する仕様:
- design.md#識別子とファイル名の規則(唯一の定義)
- requirements.md#ファイル名
"""

from __future__ import annotations

import re
from datetime import datetime

台帳の拡張子 = ".json"
urlファイルの拡張子 = ".json"
トランスクリプトの拡張子 = ".vtt"

#: 会議名・時刻・連番をつなぐ区切り。会議名に現れにくい2文字を使う。
区切り = "__"

#: ファイル名全体の長さ上限。仕様: requirements.md#ファイル名 [6]
ファイル名の長さ上限 = 120

#: 時刻の書式。分まで(秒以下は同名衝突の解消に寄与しないため持たない)。
時刻の書式 = "%Y%m%dT%H%M"

#: 会議名がすべて置換された場合に使う名前。
既定の会議名 = "untitled"

#: 会議名から取り除く、録画・中継ファイル由来の拡張子(後ろから順に剥がす)。
剥がす拡張子 = (".txt", ".mp4")

#: SharePoint/OneDriveのファイル名に使えない文字。仕様: requirements.md#ファイル名 [2]
使用できない文字 = '"*:<>?/\\|'

#: 絵文字と異体字セレクタ・ZWJ。ファイル名に残すと環境によって扱いが揺れる。
_絵文字 = re.compile(
    "[☀-➿️‍\U0001f000-\U0001faff]"
)

#: 使えない文字の置き換え先。**区切り(`__`)を構成できない文字でなければならない。**
#: `_` にすると `///` が `___` になり、区切りとの境界が判別できなくなる。
_置換文字 = "-"


def 台帳ファイル名(録画の識別子: str) -> str:
    return f"{録画の識別子}{台帳の拡張子}"


def urlファイル名(録画の識別子: str) -> str:
    return f"{録画の識別子}{urlファイルの拡張子}"


def 台帳ファイル名から識別子(ファイル名: str) -> str:
    if ファイル名.endswith(台帳の拡張子):
        return ファイル名[: -len(台帳の拡張子)]
    return ファイル名


def ファイル名の時刻を決める(
    録画の作成日時: datetime | None, 台帳の更新時刻: datetime
) -> datetime:
    """ファイル名に使う時刻を決める。

    会議の開始時刻そのものは取得できない。録画は会議終了直後に生成されるため、
    同名の定例会議を区別する目的にはどちらでも足りる。
    仕様: requirements.md#ファイル名 [4]
    """
    return 録画の作成日時 if 録画の作成日時 is not None else 台帳の更新時刻


def _拡張子を剥がす(会議名: str) -> str:
    名前 = 会議名
    変わった = True
    while 変わった:
        変わった = False
        for 拡張子 in 剥がす拡張子:
            if 名前.lower().endswith(拡張子):
                名前 = 名前[: -len(拡張子)]
                変わった = True
    return 名前


def _安全な会議名にする(会議名: str) -> str:
    """ファイル名として使える文字だけに整える。

    パス区切り文字は「使用できない文字」に含まれるため置換され、その結果として
    親ディレクトリ参照も成立しなくなる(出力置き場の外に書き出せない)。
    仕様: requirements.md#ファイル名 [2] / design.md#セキュリティ
    """
    名前 = _絵文字.sub(_置換文字, 会議名)
    名前 = "".join(_置換文字 if 文字 in 使用できない文字 else 文字 for 文字 in 名前)
    # 末尾の除去を先に行う。後にすると `定例会議...` の末尾ピリオドが
    # 置換文字に変わってしまい、除去できなくなる。
    名前 = _末尾を整える(名前)
    # 残った連続ピリオドは親ディレクトリ参照の見た目になるため畳む。
    名前 = re.sub(r"\.{2,}", _置換文字, 名前)
    return _末尾を整える(名前)


def _末尾を整える(名前: str) -> str:
    """先頭末尾の空白と末尾のピリオドを取り除く。

    切り詰めた後にも呼ぶ。切り詰めで末尾が空白やピリオドになると、
    再びファイル名の制約に触れてしまう。
    """
    return 名前.strip().rstrip(".").strip()


def 出力ファイル名(
    会議名: str,
    時刻: datetime,
    連番: int,
    *,
    長さ上限: int = ファイル名の長さ上限,
) -> str:
    """保存するトランスクリプトのファイル名を組み立てる。

    連番は**トランスクリプトが1件のときも付ける**。件数は後から増えうるため
    (requirements.md#トランスクリプトの列挙 [1])、1件目を連番なしで保存すると
    2件目が現れたときに命名規則が変わり、既存ファイルとの整合が崩れる。

    仕様: requirements.md#ファイル名
    """
    接尾辞 = (
        f"{区切り}{時刻.strftime(時刻の書式)}"
        f"{区切り}{連番:02d}{トランスクリプトの拡張子}"
    )

    名前 = _安全な会議名にする(_拡張子を剥がす(会議名))

    会議名に使える長さ = 長さ上限 - len(接尾辞)
    if len(名前) > 会議名に使える長さ:
        名前 = _末尾を整える(名前[:会議名に使える長さ])

    if not 名前:
        名前 = 既定の会議名

    return f"{名前}{接尾辞}"
