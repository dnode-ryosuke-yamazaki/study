#!/bin/bash
# UserPromptSubmitフック: 開発作業らしいユーザー入力に「開発作業なら該当する工程Skillを
# 起動してから作業する」というルーティング指示をコンテキストとして注入する。
# 工程の判定はスクリプトの語彙マッチではなくメインスレッドのモデルに任せる
# (日本語の自由入力をスクリプトで分類するのは脆いため、ここでは指示の注入だけを行う)。
# スクリプトが行うのはコストの安い足切りのみ:
#   - 開発ワードを含む入力は判定をモデルに委ねて必ず注入する
#   - 含まない場合に、挨拶・雑談・単純な質問/調査依頼など明らかに非開発な入力だけを
#     注入対象から外し、それ以外(判断が曖昧な入力)はfail-openで注入する
# 詳細は .claude/skills/README.md の「ワークフローへの自動ルーティング」を参照。

prompt=$(jq -r '.prompt // empty')

# /で始まる入力はユーザーが工程Skillを明示的に選んでいるため注入しない
case "$prompt" in
  /*) exit 0 ;;
esac

# 開発作業を示す語彙があれば、足切りをスキップして必ず注入する(判定はモデルに委ねる)
dev_pattern='実装|修正|バグ|エラー|直し|直して|直す|追加|変更|更新|削除|消して|リファクタ|テスト|PR|プルリク|レビュー|指摘|デプロイ|リリース|仕様|要件|設計|コード|ファイル|関数|コンポーネント|機能|画面|UI|フック|Skill|API|コミット|ブランチ|マージ|開発|作って|作成|npm|git|ビルド|Terraform|Lambda|インフラ'

if ! echo "$prompt" | grep -qE "$dev_pattern"; then
  # 挨拶・お礼などの雑談のみの短い入力
  chat_only_pattern='^(こんにちは|おはよう(ございます)?|こんばんは|お疲れ様(です)?|お疲れさまです|ありがとう(ございます)?|よろしく(お願いします)?|了解(です)?|OK|オーケー)[!!。、,.\ ]*$'
  # 単純な質問・調査依頼(「〜とは」「教えて」「調べて」など)
  question_pattern='とは(何|なに)?[??]?$|って(何|なに)[??]?$|について教えて|を教えて|教えてください|知りたい|ですか[??]?$|でしょうか[??]?$|調べて|調査して'

  if echo "$prompt" | grep -qE "$chat_only_pattern"; then
    exit 0
  fi
  if echo "$prompt" | grep -qE "$question_pattern"; then
    exit 0
  fi
fi

context=$(cat <<'EOF'
【ワークフロー・ルーティング】この依頼が開発作業(機能追加・既存機能の修正・仕様作成・レビュー・指摘対応・PR作成)に該当する場合、必ず該当する工程Skill(.claude/skills/README.md参照)をSkillツールで起動してから作業を始めること。
- 入口の判定: 新しい機能・アプリ → /requirement、既存機能のバグ・小規模改修 → /fix、方針の壁打ち → /consult
- 工程の途中の依頼(「実装して」「レビューして」等)は、そのSkill冒頭の「前提条件」を確認し、前工程の成果物が揃っていなければ上流の工程Skillから始める(要件定義より前にコードを書かない)
- ユーザーが「autopilotで」「自動で最後まで」のように自走を指示した場合は /autopilot(小規模・低リスクの変更限定)を起動する
- 定期作業(振り返り)はユーザーが `/retrospective` のように明示起動する。自律起動はできないので、ここでは扱わない
- どの工程にも該当しない依頼(質問・調査・説明のみ)はSkillを起動せずそのまま回答してよい
EOF
)

jq -n --arg ctx "$context" '{hookSpecificOutput: {hookEventName: "UserPromptSubmit", additionalContext: $ctx}}'
